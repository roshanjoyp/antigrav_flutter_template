/// Generates and verifies module combinations:
///   dart run craft_generator:verify_matrix [--tier quick|full]
///       [--template-root DIR]
///
/// quick: all-on, all-off, each module solo (+push⇒firebase), analyze
/// gate — the pre-commit sweep. full: all 12 valid combos, with the
/// full test gate on all-on and all-off — the pre-release sweep.
library;

// ignore_for_file: avoid_print

import 'dart:io';

import 'package:craft_generator/craft_generator.dart';
import 'package:path/path.dart' as p;

const _order = ['firebase', 'revenuecat', 'push', 'onboarding'];

List<Map<String, bool>> _combos(String tier) {
  if (tier == 'quick') {
    return [
      {for (final id in _order) id: true},
      {for (final id in _order) id: false},
      {'firebase': true},
      {'revenuecat': true},
      {'onboarding': true},
      {'firebase': true, 'push': true},
    ];
  }
  final combos = <Map<String, bool>>[];
  for (var bits = 0; bits < 16; bits++) {
    final combo = {
      for (var i = 0; i < _order.length; i++) _order[i]: (bits >> i) & 1 == 1,
    };
    if (combo['push']! && !combo['firebase']!) continue; // invalid
    combos.add(combo);
  }
  return combos;
}

String _label(Map<String, bool> combo) {
  final on = _order.where((id) => combo[id] ?? false).toList();
  if (on.isEmpty) return 'none';
  if (on.length == _order.length) return 'all';
  return on.join('+');
}

void main(List<String> args) {
  var tier = 'quick';
  String? templateRoot;
  for (var i = 0; i < args.length; i++) {
    switch (args[i]) {
      case '--tier':
        tier = args[++i];
      case '--template-root':
        templateRoot = args[++i];
      default:
        stderr.writeln('unknown flag: ${args[i]}');
        exit(64);
    }
  }
  if (tier != 'quick' && tier != 'full') {
    stderr.writeln('--tier must be quick or full');
    exit(64);
  }

  final cwd = Directory.current.path;
  final root = Directory(
    templateRoot ??
        (File(p.join(cwd, 'setup', 'setup.dart')).existsSync()
            ? cwd
            : p.dirname(cwd)),
  );

  final results = <String, GenerateResult>{};
  final stopwatch = Stopwatch()..start();
  for (final combo in _combos(tier)) {
    final label = _label(combo);
    final isExtreme = label == 'all' || label == 'none';
    final gate = tier == 'full' && isExtreme
        ? GateLevel.test
        : GateLevel.analyze;
    stdout.write('▶ $label (${gate.name}) … ');
    final result = generate(
      GeneratorConfig.fromJson({
        'appName': 'Matrix Probe',
        'packageId': 'com.example.matrixprobe',
        'description': 'Generated by the verify matrix for compile proof.',
        'modules': combo,
      }),
      templateRoot: root,
      outPath: p.join(
        Directory.systemTemp.path,
        'craft_matrix_${label.replaceAll('+', '_')}.zip',
      ),
      gate: gate,
    );
    results[label] = result;
    print(result.ok ? '✓' : '✗');
    if (!result.ok) {
      print('  ${result.log.last}');
      if (result.stagingPath != null) {
        print('  staging kept: ${result.stagingPath}');
      }
    }
  }
  stopwatch.stop();

  final failed = results.entries.where((e) => !e.value.ok).toList();
  print('\n${'─' * 46}');
  print(
    '${results.length - failed.length}/${results.length} combos passed '
    'in ${stopwatch.elapsed.inSeconds}s ($tier tier).',
  );
  for (final entry in failed) {
    print('  ✗ ${entry.key}');
  }
  exit(failed.isEmpty ? 0 : 1);
}
